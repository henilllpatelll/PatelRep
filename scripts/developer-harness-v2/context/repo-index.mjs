#!/usr/bin/env node
// Developer Harness V2 — Phase 3 small repository index (replaces the stale OpenWolf anatomy).
//
// Writes `.wolf/anatomy.md`: a PARTIAL, high-level map (directories with tracked-file counts plus key manifests)
// generated on demand from `git ls-tree` at a commit. Deterministic for a given commit: the "scan date" is that
// commit's committer date, not the wall clock. Generated, cached, binary and credential paths are excluded.
// No automatic rescans: run it only when asked.
//
//   node repo-index.mjs --repo <dir> [--commit HEAD] [--out .wolf/anatomy.md] [--stdout]
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { exclusionReason } from './context-packs.mjs'

/** Directories expanded one level deeper; everything else is listed at top level only. */
export const EXPAND = Object.freeze(['apps/api', 'apps/web', 'apps/mobile', 'supabase', 'scripts', 'docs', '.github', 'packages'])
export const KEY_FILES = Object.freeze([
  'CLAUDE.md', 'AGENTS.md', 'package.json', 'apps/api/main.py', 'apps/api/requirements.txt', 'apps/api/RBAC-MATRIX.md',
  'apps/web/package.json', 'apps/web/AGENTS.md', 'apps/mobile/package.json', 'apps/mobile/app.json',
  'docs/developer-harness-v2/contract.json', '.claude/settings.json', '.wolf/cerebrum.md',
])
export const MAX_INDEX_BYTES = 12_000

const git = (repo, args) => execFileSync('git', ['-C', repo, ...args], { maxBuffer: 1 << 28 }).toString('utf8')

export function buildIndex({ files, commit, date }) {
  const kept = files.filter((f) => !exclusionReason(f))
  const excluded = files.length - kept.length
  const count = (prefix) => kept.filter((f) => f.startsWith(`${prefix}/`)).length
  const tops = [...new Set(kept.map((f) => (f.includes('/') ? f.split('/')[0] : null)).filter(Boolean))].sort()
  const lines = [
    '# Repository index (partial)',
    '',
    `> Generated by \`scripts/developer-harness-v2/context/repo-index.mjs\` from \`${commit.slice(0, 12)}\` (commit date ${date}).`,
    `> **Partial map, not complete coverage:** ${kept.length} tracked files indexed by directory; ${excluded} generated, cached,`,
    '> binary or credential-like paths excluded. Not refreshed automatically: re-run the script on request.',
    '> If a file is not listed here, use ordinary repository search (`rg`, Glob). The pre-Phase-3 anatomy is archived',
    '> (see `docs/developer-harness-v2/08-phase-3-context-and-memory-report.md`).',
    '',
    '## Top-level directories',
    '',
    '| Directory | Tracked files |',
    '|---|---|',
    ...tops.map((t) => `| \`${t}/\` | ${count(t)} |`),
    '',
    '## Subsystems',
    '',
  ]
  for (const base of EXPAND) {
    const subs = [...new Set(kept.filter((f) => f.startsWith(`${base}/`)).map((f) => f.slice(base.length + 1).split('/')).filter((p) => p.length > 1).map((p) => p[0]))].sort()
    if (!subs.length) continue
    lines.push(`### \`${base}/\` (${count(base)} files)`, '', subs.map((s) => `\`${s}/\` ${count(`${base}/${s}`)}`).join(' · '), '')
  }
  lines.push('## Key files', '', ...KEY_FILES.filter((f) => kept.includes(f)).map((f) => `- \`${f}\``), '')
  return lines.join('\n')
}

function parseArgs(argv) {
  const opts = {}
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--stdout') opts.stdout = true
    else opts[argv[i].replace(/^--/, '')] = argv[++i]
  }
  return opts
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const opts = parseArgs(process.argv.slice(2))
  const repo = opts.repo ?? '.'
  const commit = git(repo, ['rev-parse', '--verify', `${opts.commit ?? 'HEAD'}^{commit}`]).trim()
  const date = git(repo, ['show', '-s', '--format=%cs', commit]).trim()
  const files = git(repo, ['ls-tree', '-r', '-z', '--name-only', commit]).split('\0').filter(Boolean)
  const text = buildIndex({ files, commit, date })
  if (opts.stdout) console.log(text)
  else writeFileSync(path.resolve(repo, opts.out ?? '.wolf/anatomy.md'), text)
  console.error(JSON.stringify({ bytes: Buffer.byteLength(text), commit }))
}
